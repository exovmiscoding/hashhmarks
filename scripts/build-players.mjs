/**
 * Builds shared/players.mjs from ESPN's public rosters.
 *
 * Rarity is assigned per club from ESPN's roster order (offense first, depth
 * order within a unit) so every team contributes one legendary, two epics and
 * eight rares, and every draw can reach all 32 franchises.
 */
import { writeFile, mkdir } from 'node:fs/promises';

const TEAMS_URL = 'https://site.api.espn.com/apis/site/v2/sports/football/nfl/teams?limit=40';
const rosterUrl = (id) =>
  `https://site.api.espn.com/apis/site/v2/sports/football/nfl/teams/${id}/roster`;

const ABBR_FIX = { WSH: 'WAS', JAC: 'JAX', LA: 'LAR', OAK: 'LV', SD: 'LAC', STL: 'LAR' };

function rarityFor(index) {
  if (index === 0) return 'legendary';
  if (index <= 2) return 'epic';
  if (index <= 10) return 'rare';
  return 'common';
}

const teamsPayload = await (await fetch(TEAMS_URL)).json();
const teams = teamsPayload.sports[0].leagues[0].teams.map((entry) => entry.team);
console.log(`teams: ${teams.length}`);

const players = [];
const seen = new Set();

for (const team of teams) {
  const abbr = ABBR_FIX[team.abbreviation] ?? team.abbreviation;
  const response = await fetch(rosterUrl(team.id));
  if (!response.ok) {
    console.log(`  ${abbr}: roster ${response.status}, skipped`);
    continue;
  }
  const roster = await response.json();
  const athletes = (roster.athletes ?? []).flatMap((group) => group.items ?? []).filter(Boolean);

  let index = 0;
  for (const athlete of athletes) {
    if (!athlete?.id || !athlete.fullName || seen.has(athlete.id)) continue;
    seen.add(athlete.id);
    players.push({
      id: String(athlete.id),
      name: athlete.fullName,
      position: athlete.position?.abbreviation ?? '',
      team: abbr,
      jersey: athlete.jersey ?? null,
      experience: athlete.experience?.years ?? null,
      college: athlete.college?.name ?? null,
      height: athlete.displayHeight ?? null,
      weight: athlete.displayWeight ?? null,
      headshot: athlete.headshot?.href ?? `https://a.espncdn.com/i/headshots/nfl/players/full/${athlete.id}.png`,
      rarity: rarityFor(index),
    });
    index += 1;
  }

  console.log(`  ${abbr}: ${index} cards`);
  await new Promise((resolve) => setTimeout(resolve, 120));
}

const counts = players.reduce((acc, player) => {
  acc[player.rarity] = (acc[player.rarity] ?? 0) + 1;
  return acc;
}, {});
const clubs = new Set(players.map((player) => player.team));

await mkdir('shared', { recursive: true });
const source = `// Generated by scripts/build-players.mjs from ESPN public rosters. Do not edit by hand.
export const PLAYERS = ${JSON.stringify(players)};
`;
await writeFile('shared/players.mjs', source, 'utf8');

console.log(`\ntotal: ${players.length} players across ${clubs.size} clubs`);
console.log('rarity:', JSON.stringify(counts));
